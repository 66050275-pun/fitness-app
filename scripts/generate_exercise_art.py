"""Generate local artwork imports and exact credits from the pinned, installed package.

Run after changing exerciseCatalog.json. Source PNGs are never modified.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "node_modules/@bryllim/workout-guide"


def generate() -> None:
    version = json.loads((PACKAGE / "package.json").read_text())["version"]
    if version != "1.0.0":
        raise ValueError("Review artwork/licensing before changing the pinned library version.")
    catalog = json.loads((ROOT / "src/data/exerciseCatalog.json").read_text())
    source = {row["slug"]: row for row in json.loads((PACKAGE / "manifest.json").read_text())}
    slugs = sorted({row["artworkSlug"] for row in catalog} | {"plank"})
    imports, entries, credits = [], [], []
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    for index, slug in enumerate(slugs):
        exercise = source[slug]
        selected = [exercise["frames"][0], exercise["frames"][2]]
        for frame in selected:
            path = (PACKAGE / frame["path"]).resolve()
            if not path.is_relative_to(PACKAGE.resolve()) or not path.is_file():
                raise ValueError("Missing or unexpected artwork path: " + slug)
            if frame["attribution"]["license"] != "CC BY-SA 4.0":
                raise ValueError("Review changed artwork license: " + slug)
            imports.append(f"import image{index}_{frame['index']} from '@bryllim/workout-guide/{frame['path']}?no-inline';")
        attribution = exercise["attribution"]
        upstream = attribution.get("source")
        credit = attribution["creator"] + (" / " + upstream["name"] if upstream else "")
        url = upstream["url"] if upstream else "https://bryllim.github.io/workout-guide/"
        entries.append(f"  {quote(slug)}: {{ frames: [image{index}_1, image{index}_3], sourceName: {quote(exercise['name'])}, credit: {quote(credit)}, sourceUrl: {quote(url)} }},")
    for row in [*catalog, {"name": "Plank", "artworkSlug": "plank"}]:
        exercise = source[row["artworkSlug"]]
        credits.append({"appExercise": row["name"], "appAliases": row.get("aliases", []), "libraryExercise": exercise["name"], "slug": exercise["slug"],
                        "note": row.get("artworkNote"), "attribution": exercise["attribution"],
                        "frames": [exercise["frames"][0], exercise["frames"][2]]})
    header = "// Generated by scripts/generate_exercise_art.py; do not edit image imports by hand.\n"
    interface = """
import { EXERCISE_CATALOG, normalizeExerciseName } from './exerciseCatalog.ts';

export interface ExerciseArtwork {
  frames: readonly [string, string];
  sourceName: string;
  credit: string;
  sourceUrl: string;
  note?: string;
}
const bySlug: Record<string, ExerciseArtwork> = {
"""
    footer = """};
export const exerciseArtwork: Record<string, ExerciseArtwork> = Object.fromEntries([
  ...EXERCISE_CATALOG.flatMap(exercise => [exercise.name, ...exercise.aliases].map(name => [name,
    { ...bySlug[exercise.artworkSlug], note: exercise.artworkNote }] as const)),
  ['Plank', bySlug.plank],
]);
const byName = new Map(Object.entries(exerciseArtwork).map(([name, artwork]) => [normalizeExerciseName(name), artwork]));

export function findExerciseArtwork(name: string): ExerciseArtwork | undefined {
  return byName.get(normalizeExerciseName(name));
}
"""
    (ROOT / "src/data/exerciseArtwork.ts").write_text(header + "\n".join(imports) + "\n" + interface + "\n".join(entries) + "\n" + footer)
    attribution = {"package": "@bryllim/workout-guide", "version": version, "license": "CC BY-SA 4.0",
                   "licenseUrl": "https://creativecommons.org/licenses/by-sa/4.0/",
                   "changes": "Images are unchanged. CSS scales them on a contrasting background. The existing incline-fly variant is explicitly noted.",
                   "exercises": credits}
    (ROOT / "docs/exercise-art/ATTRIBUTION.json").write_text(json.dumps(attribution, ensure_ascii=False, indent=2) + "\n")
    print(f"Generated {len(slugs) * 2} unchanged frame imports and {len(credits)} app exercise credits.")


if __name__ == "__main__":
    generate()
